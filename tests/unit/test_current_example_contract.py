"""Committed current examples must follow the artifact the package writes now.

``examples/audit_churn`` is the illustration a reader opens. If the artifact
schema moves and those files stay behind, this test fails until they are
regenerated by ``examples/audit_churn/generate_artifacts.py``.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd
import pytest

from aidatasetkit import __version__
from aidatasetkit.core import KitConfig
from aidatasetkit.evidence import (
    ARTIFACT_SCHEMA_VERSION,
    PUBLICATION_SCHEMA_VERSION,
    canonical_json,
    render_report,
)
from aidatasetkit.evidence.fingerprint import config_fingerprint
from tests.golden import pandas_major, semantic_fixture_path

EXAMPLE = Path(__file__).resolve().parents[2] / "examples" / "audit_churn"
CURRENT_OUTPUTS = ("audit.json", "lineage.json", "report.html")
FORBIDDEN_FRAGMENTS = ("/home/", "/tmp/", "/Users/", "/var/", "C:\\", ".venv", "scratch/")


def _load(name: str):
    return json.loads((EXAMPLE / name).read_text(encoding="utf-8"))


def _semantic_view(payload: dict) -> dict:
    """The illustrative audit without the clock, the environment, or the file label."""
    view = {key: value for key, value in payload.items() if key != "provenance"}
    dataset = dict(view["dataset"])
    dataset.pop("name", None)
    view["dataset"] = dataset
    return view


def _blob() -> str:
    return "\n".join((EXAMPLE / name).read_text(encoding="utf-8") for name in (
        *CURRENT_OUTPUTS,
        "expected_audit_semantic.json",
        "expected_audit_semantic.pandas2.json",
    ))


class TestCommittedCurrentExamples:
    @pytest.mark.parametrize(
        "name", ["expected_audit_semantic.json", "expected_audit_semantic.pandas2.json"]
    )
    def test_pandas_major_datetime_fixture_contract(self, name):
        fixture = _load(name)
        assert fixture["schema_version"] == ARTIFACT_SCHEMA_VERSION == "1.5", (
            "pandas-major datetime fixture contract"
        )
        settings = fixture["config"]["settings"]
        assert settings["thresholds"] == KitConfig().to_dict(), (
            "pandas-major datetime fixture contract"
        )
        assert fixture["config"]["fingerprint"] == config_fingerprint(settings), (
            "pandas-major datetime fixture contract"
        )
        for column in fixture["columns"]:
            assert "datetime" in column and column["datetime"] is None, (
                "pandas-major datetime fixture contract"
            )
        assert fixture["verdict"] == "blocked"

    def test_the_current_outputs_use_the_live_schema(self):
        audit = _load("audit.json")
        lineage = _load("lineage.json")
        assert ARTIFACT_SCHEMA_VERSION == "1.5"
        assert audit["schema_version"] == ARTIFACT_SCHEMA_VERSION
        assert lineage["schema_version"] == ARTIFACT_SCHEMA_VERSION
        assert PUBLICATION_SCHEMA_VERSION == "1.0"
        assert __version__ == "0.1.0a1"

    def test_the_audit_matches_the_model_the_code_builds(self):
        root = str(EXAMPLE.parents[1])
        if root not in sys.path:
            sys.path.insert(0, root)
        from examples.audit_churn.generate_artifacts import build_artifact

        audit = _load("audit.json")
        reference = _load("expected_audit_semantic.json")
        rebuilt = build_artifact(pd.read_csv(EXAMPLE / "train.csv")).semantic_dict()
        fixture = json.loads(semantic_fixture_path().read_text(encoding="utf-8"))
        # The committed illustration is the pandas 3 reference. Pandas 2 rebuilds
        # against its own fixture; dtype names are the only allowed gap.
        assert _semantic_view(audit) == reference
        assert rebuilt == fixture
        assert rebuilt["schema_version"] == reference["schema_version"] == ARTIFACT_SCHEMA_VERSION
        assert rebuilt["date_inference"] == reference["date_inference"] == audit["date_inference"]
        if pandas_major() == 3:
            assert canonical_json(rebuilt) == (EXAMPLE / "expected_audit_semantic.json").read_text(
                encoding="utf-8"
            )
            assert audit["provenance"]["semantic_fingerprint"] == config_fingerprint(rebuilt)
        else:
            assert audit["provenance"]["semantic_fingerprint"] == config_fingerprint(reference)
        assert audit["provenance"]["created_at"] == "2025-02-01T00:00:00Z"
        assert lineage_fingerprint(audit, _load("lineage.json"))

    def test_date_inference_is_the_typed_record(self):
        record = _load("audit.json")["date_inference"]
        assert record == {
            "method": "strict_iso_full_population_v1",
            "population": "full",
            "full_population_scanned": True,
            "minimum_non_blank": 8,
            "required_match_ratio": 1.0,
            "conversion_performed": False,
            "affects_detected_kind": False,
            "affects_verdict": False,
            "columns": [],
        }
        assert record["conversion_performed"] is False
        assert record["affects_detected_kind"] is False
        assert record["affects_verdict"] is False

    def test_the_semantic_fixtures_carry_the_same_date_record(self):
        audit = _load("audit.json")["date_inference"]
        reference = _load("expected_audit_semantic.json")
        pandas2 = _load("expected_audit_semantic.pandas2.json")
        assert reference["schema_version"] == ARTIFACT_SCHEMA_VERSION
        assert pandas2["schema_version"] == ARTIFACT_SCHEMA_VERSION
        assert reference["date_inference"] == audit
        assert pandas2["date_inference"] == audit
        assert reference["dataset"]["fingerprint"] == _load("audit.json")["dataset"]["fingerprint"]

    def test_the_html_renders_that_audit_and_does_not_claim_conversion(self):
        audit = _load("audit.json")
        page = (EXAMPLE / "report.html").read_text(encoding="utf-8")
        assert page == render_report(audit)
        assert f"Artifact schema {ARTIFACT_SCHEMA_VERSION}." in page
        assert "Date inference" in page
        assert "strict_iso_full_population_v1" in page
        assert "Full population scanned: True" in page
        assert "Conversion performed: no" in page
        assert "detected kind unchanged" in page
        assert "was not converted" in page
        assert "not datetime-profiled" in page
        assert "No textual column met the strict ISO rule." in page
        assert "<td>categorical</td>" in page

    def test_the_examples_carry_no_local_path(self):
        text = _blob()
        workspace = str(EXAMPLE.parents[1])
        assert workspace not in text
        for fragment in FORBIDDEN_FRAGMENTS:
            assert fragment not in text
        environment = _load("audit.json")["provenance"]["environment"]
        assert set(environment) == {
            "aidatasetkit",
            "python",
            "numpy",
            "pandas",
            "scipy",
            "scikit_learn",
        }
        assert environment["aidatasetkit"] == __version__
        for value in environment.values():
            assert "/" not in value and "\\" not in value


def lineage_fingerprint(audit: dict, lineage: dict) -> bool:
    assert lineage["dataset_fingerprint"] == audit["dataset"]["fingerprint"]
    assert lineage["stage"] == audit["stage"]
    return True
